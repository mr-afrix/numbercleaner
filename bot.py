async def cmd_file(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    uid = update.effective_user.id
    if await check_ban_gate(update, ctx, uid): return
    if await check_membership_gate(update, ctx, uid): return
    doc = update.message.document
    name = doc.file_name or "file.csv"
    ext = name.lower().rsplit(".", 1)[-1]
    if ext not in ("csv", "xlsx", "xls", "txt", "json", "xml", "vcf"):
        await update.message.reply_text("Unsupported format.", reply_markup=retry_kb(uid))
        return
    msg = await update.message.reply_text(f"`[{pbar(0)}]` {t('reading_file', uid)}", parse_mode=ParseMode.MARKDOWN)
    try:
        tg = await ctx.bot.get_file(doc.file_id)
        raw = bytes(await tg.download_as_bytearray())
        await msg.edit_text(f"`[{pbar(3)}]` {t('parsing_numbers', uid)}", parse_mode=ParseMode.MARKDOWN)
        loop = asyncio.get_event_loop()
        result = await loop.run_in_executor(None, process, raw, name)
        await msg.edit_text(f"`[{pbar(8)}]` {t('grouping', uid)}", parse_mode=ParseMode.MARKDOWN)
        ctx.user_data["result"] = result
        await msg.edit_text(f"`[{pbar(10)}]` {t('done', uid)}\n\n" + build_summary(result, uid), parse_mode=ParseMode.MARKDOWN, reply_markup=fmt_keyboard(uid))
    except Exception as e:
        logging.error(f"Error processing file: {e}\n{traceback.format_exc()}")
        await msg.edit_text(t("failed_process", uid), reply_markup=retry_kb(uid))

async def cmd_forward(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    uid = update.effective_user.id
    rec = db_get(uid)
    if not rec.get("awaiting_channel"):
        return
    fwd = update.message.forward_origin
    if not fwd:
        await update.message.reply_text(t("fwd_message", uid), reply_markup=back_kb(uid))
        return
    try:
        chat_id = fwd.chat.id
        title = fwd.chat.title or str(chat_id)
        db_update(uid, channel=chat_id, channel_title=title, awaiting_channel=False)
        await update.message.reply_text(f"[OK] {t('channel_linked', uid)} : `{title}`", parse_mode=ParseMode.MARKDOWN, reply_markup=main_menu_kb(uid))
    except Exception:
        await update.message.reply_text(t("could_not_read", uid), reply_markup=back_kb(uid))

async def cmd_callback(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    q = update.callback_query
    uid = q.from_user.id
    await q.answer()
    d = q.data
    if d == "recheck":
        if await check_membership_gate(update, ctx, uid): return
        await q.edit_message_text(f"[OK] *{t('access_granted', uid)}*", parse_mode=ParseMode.MARKDOWN)
        await asyncio.sleep(0.4)
        await show_main_menu(q, uid, edit=True)
        return
    if d == "menu:back":
        await show_main_menu(q, uid, edit=True)
        return
    if d == "menu:info":
        await q.edit_message_text(f"*{t('send_file', uid)}* *\n\nTXT, CSV, XLSX, XLS, JSON, XML, VCF", parse_mode=ParseMode.MARKDOWN, reply_markup=back_kb(uid))
        return
    if d == "menu:addch":
        db_update(uid, awaiting_channel=True)
        await q.edit_message_text(f"*{t('add_channel', uid)}* *\n\n{t('add_channel_inst', uid)}", parse_mode=ParseMode.MARKDOWN, reply_markup=back_kb(uid))
        return
    if d == "menu:rmch":
        db_update(uid, channel=None, channel_title=None, awaiting_channel=False)
        await q.edit_message_text(f"[OK] {t('channel_removed', uid)}", parse_mode=ParseMode.MARKDOWN, reply_markup=main_menu_kb(uid))
        return
    if d == "menu:settings":
        await q.edit_message_text(f"*{t('settings', uid)}*", parse_mode=ParseMode.MARKDOWN, reply_markup=settings_kb(uid))
        return
    if d == "menu:stats":
        rec = db_get(uid)
        stats = f"*{t('stats', uid)}*\nUID: {uid}\nLANG: {rec.get('lang')}\nPREMIUM: {rec.get('premium')}\nJOINED: {rec.get('joined_date')}"
        await q.edit_message_text(stats, parse_mode=ParseMode.MARKDOWN, reply_markup=back_kb(uid))
        return
    if d == "settings:lang":
        await q.edit_message_text(t("select_lang", uid), reply_markup=lang_kb())
        return
    if d.startswith("setlang:"):
        lang = d.split(":")[1]
        db_update(uid, lang=lang)
        await q.edit_message_text(t("lang_updated", uid), reply_markup=settings_kb(uid))
        return
    if d.startswith("format:"):
        fmt = d.split(":")[1]
        await q.edit_message_text(f"Format: {fmt}. Choose export type:", reply_markup=type_keyboard(uid, fmt))
        return
    if d.startswith("send:"):
        if await check_membership_gate(update, ctx, uid): return
        result = ctx.user_data.get("result")
        if not result:
            await q.edit_message_text(t("session_expired", uid), reply_markup=retry_kb(uid))
            return
        parts = d.split(":")
        export_type = parts[1]
        use_plus = parts[2] == "plus"
        await q.edit_message_reply_markup(reply_markup=None)
        total_files = len(result["groups"]) + (1 if result["unknown"] else 0)
        prog = await ctx.bot.send_message(uid, f"`[{pbar(0)}]` {t('preparing_files', uid)}", parse_mode=ParseMode.MARKDOWN)
        groups = result["groups"]
        unknown = result["unknown"]
        sent = 0
        rec = db_get(uid)
        linked = rec.get("channel")
        sorted_groups = sorted(groups.items(), key=lambda x: -len(x[1]["numbers"]))
        all_files = []
        for iso, v in sorted_groups:
            nums = [f"+{n}" if use_plus else n for n in v["numbers"]]
            fname = f"{v['name'].upper().replace(' ', '_')}.{export_type}"
            if export_type == "vcf":
                buf = io.BytesIO(build_vcf(nums, v['name']))
            elif export_type == "xml":
                buf = io.BytesIO(build_xml(nums, v['name']))
            elif export_type == "json":
                buf = io.BytesIO(build_json(nums, v['name']))
            else:
                buf = io.BytesIO("\n".join(nums).encode())
                
            cap = f"{iso_to_flag(iso)} {sc(v['name'].upper())}\n{t('country_code', uid)} : +{v['dial']}\n{t('total_numbers', uid)} : {len(nums)}"
            all_files.append((buf, fname, cap))
            
        if unknown:
            nums = [f"+{n}" if use_plus else n for n in unknown]
            fname = f"UNKNOWN.{export_type}"
            if export_type == "vcf":
                buf = io.BytesIO(build_vcf(nums, "Unknown"))
            elif export_type == "xml":
                buf = io.BytesIO(build_xml(nums, "Unknown"))
            elif export_type == "json":
                buf = io.BytesIO(build_json(nums, "Unknown"))
            else:
                buf = io.BytesIO("\n".join(nums).encode())
            cap = f"[?] {t('unknown', uid)}\n{t('total_numbers', uid)} : {len(nums)}"
            all_files.append((buf, fname, cap))
            
        last_idx = len(all_files) - 1
        for i, (buf, fname, cap) in enumerate(all_files):
            is_last = (i == last_idx)
            kb = again_kb(uid) if is_last else None
            await ctx.bot.send_document(chat_id=uid, document=buf, filename=fname, caption=cap, reply_markup=kb)
            if linked:
                buf.seek(0)
                try:
                    await ctx.bot.send_document(chat_id=linked, document=buf, filename=fname, caption=cap)
                except TelegramError:
                    pass
            sent += 1
            step = round(sent / total_files * 10)
            await prog.edit_text(f"`[{pbar(step)}]` {t('sending', uid)} {sent}/{total_files}", parse_mode=ParseMode.MARKDOWN)
            await asyncio.sleep(0.25)
        ctx.user_data.pop("result", None)
        await prog.edit_text(f"`[{pbar(10)}]` * {t('done', uid)} : {sent} {t('file_sent', uid)}", parse_mode=ParseMode.MARKDOWN)

async def inline_query(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    query = update.inline_query.query
    if not query:
        return
    results = []
    for iso, data in COUNTRIES_DATA.items():
        if query.lower() in data['name'].lower() or query.lower() in iso.lower():
            text = f"Country: {data['name']}\nISO2: {iso}\nISO3: {data['iso3']}\nNumeric: {data['numeric']}"
            results.append(InlineQueryResultArticle(
                id=iso,
                title=data['name'],
                description=f"ISO: {iso}",
                input_message_content=InputTextMessageContent(text)
            ))
        if len(results) >= 50:
            break
    await update.inline_query.answer(results)

