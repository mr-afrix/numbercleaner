def build_summary(result: dict, uid: int) -> str:
    groups = result["groups"]
    unknown = result["unknown"]
    clean = sum(len(v["numbers"]) for v in groups.values()) + len(unknown)
    lines = [f"*{t('file_processed', uid)}* *\n"]
    lines.append(f"{t('received', uid)} : `{result['total']}`")
    lines.append(f"{t('duplicates', uid)} : `{result['dupes']}`")
    lines.append(f"{t('clean', uid)} : `{clean}`")
    lines.append(f"{t('countries', uid)} : `{len(groups)}`\n")
    for iso, v in sorted(groups.items(), key=lambda x: -len(x[1]["numbers"])):
        lines.append(f"{iso_to_flag(iso)} *{sc(v['name'].upper())}*  `+{v['dial']}` : `{len(v['numbers'])}` {t('numbers', uid)}")
    if unknown:
        lines.append(f"[?] *{t('unknown', uid)}* : `{len(unknown)}` {t('numbers', uid)}")
    lines.append(f"\n{t('choose_format', uid)}")
    return "\n".join(lines)

