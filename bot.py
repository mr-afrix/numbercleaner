def parse_number(raw: str):
    clean = "".join(filter(str.isdigit, raw))
    if not (7 <= len(clean) <= 15):
        return None, None, None, None, None, None
    try:
        p = phonenumbers.parse("+" + clean)
        if not phonenumbers.is_valid_number(p):
            return clean, None, None, None, None, None
        iso = region_code_for_number(p)
        if not iso:
            return clean, None, None, None, None, None
        cname = iso_to_name(iso)
        dial = country_code_for_region(iso)
        car = carrier.name_for_number(p, "en")
        tz = timezone.time_zones_for_number(p)
        tz_str = tz[0] if tz else "Unknown"
        return clean, iso, cname, dial, car, tz_str
    except Exception:
        return clean, None, None, None, None, None

def detect_number_column(df: pd.DataFrame) -> str:
    priority = {"number", "phone", "phone number", "msisdn", "mobile", "tel", "telephone", "contact"}
    for col in df.columns:
        if str(col).strip().lower() in priority:
            return col
    for col in df.columns:
        sample = df[col].dropna().astype(str).head(20)
        ratio = sample.str.replace(r"\D", "", regex=True).str.len().between(7, 15).mean()
        if ratio >= 0.6:
            return col
    raise ValueError("no phone column found")

def parse_xml_to_df(data: bytes) -> pd.DataFrame:
    root = ET.fromstring(data.decode('utf-8'))
    all_records = []
    for child in root:
        record = {}
        for subchild in child:
            record[subchild.tag] = subchild.text
        all_records.append(record)
    return pd.DataFrame(all_records)

def parse_json_to_df(data: bytes) -> pd.DataFrame:
    return pd.read_json(io.BytesIO(data))

def parse_txt_to_df(data: bytes) -> pd.DataFrame:
    lines = data.decode('utf-8').splitlines()
    return pd.DataFrame({"phone": lines})

def parse_vcf_to_df(data: bytes) -> pd.DataFrame:
    lines = data.decode('utf-8').splitlines()
    phones = []
    for line in lines:
        if line.startswith("TEL"):
            parts = line.split(":")
            if len(parts) > 1:
                phones.append(parts[1])
    return pd.DataFrame({"phone": phones})

def load_file(data: bytes, name: str) -> pd.DataFrame:
    n = name.lower()
    if n.endswith(".csv"):
        return pd.read_csv(io.BytesIO(data))
    if n.endswith(".xlsx"):
        return pd.read_excel(io.BytesIO(data), engine="openpyxl")
    if n.endswith(".xls"):
        return pd.read_excel(io.BytesIO(data), engine="xlrd")
    if n.endswith(".xml"):
        return parse_xml_to_df(data)
    if n.endswith(".json"):
        return parse_json_to_df(data)
    if n.endswith(".txt"):
        return parse_txt_to_df(data)
    if n.endswith(".vcf"):
        return parse_vcf_to_df(data)
    raise ValueError("unsupported format")

def build_vcf(numbers: list, name: str) -> bytes:
    lines = []
    for i, num in enumerate(numbers):
        lines.append("BEGIN:VCARD")
        lines.append("VERSION:3.0")
        lines.append(f"FN:{name} {i+1}")
        lines.append(f"TEL;TYPE=CELL:{num}")
        lines.append("END:VCARD")
    return "\n".join(lines).encode('utf-8')

def build_xml(numbers: list, name: str) -> bytes:
    root = ET.Element("Contacts")
    for num in numbers:
        contact = ET.SubElement(root, "Contact")
        phone = ET.SubElement(contact, "Phone")
        phone.text = str(num)
    return ET.tostring(root, encoding='utf-8')

def build_json(numbers: list, name: str) -> bytes:
    return json.dumps([{"phone": num} for num in numbers]).encode('utf-8')

def process(data: bytes, name: str) -> dict:
    df = load_file(data, name)
    col = detect_number_column(df)
    raw = df[col].dropna().astype(str).tolist()
    total = len(raw)
    seen = set()
    groups = {}
    unknown = []
    dupes = 0
    for r in raw:
        num, iso, cname, dial, car, tz = parse_number(r)
        if num is None:
            continue
        if num in seen:
            dupes += 1
            continue
        seen.add(num)
        if iso:
            if iso not in groups:
                groups[iso] = {"name": cname, "dial": dial, "numbers": [], "carriers": set(), "timezones": set()}
            groups[iso]["numbers"].append(num)
            if car:
                groups[iso]["carriers"].add(car)
            if tz:
                groups[iso]["timezones"].add(tz)
        else:
            unknown.append(num)
    return {"groups": groups, "unknown": unknown, "dupes": dupes, "total": total}

async def membership(bot, uid: int) -> list:
    out = []
    for ch in CHANNELS:
        try:
            m = await bot.get_chat_member(ch["id"], uid)
            if m.status in ("left", "kicked", "banned"):
                out.append(ch)
        except TelegramError:
            out.append(ch)
    return out

